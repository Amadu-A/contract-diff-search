def system_prompt(mode: str, kind: str) -> str:
    """Собирает отдельные инструкции режима и вида проверки с фиксированной версией схемы."""
    return "Версия промпта: 2.\n" + COMMON + "\n" + MODES[mode] + "\n" + TASKS[kind]
